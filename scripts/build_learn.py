    members = [a for a in articles if a["meta"]["pillar"] == pillar["key"] and a is not guide]
    title = guide["meta"]["title"] if guide else pillar["title"]
    description = guide["meta"]["description"] if guide else f"{pillar['title']}: {pillar['blurb']}"
    keywords = guide["meta"]["keywords"] if guide else f"{pillar['title'].lower()}, walking health, walking benefits"
    graph = org_nodes()
    if guide:
        graph += article_graph(guide, path, pillar, image)
        graph[-1].pop("isPartOf")
        graph[-1]["isPartOf"] = {"@id": url("/learn/") + "#webpage"}
        if guide["faq"]:
            graph.append(faq_node(path, guide["faq"]))
    else:
        graph.append({"@type": "CollectionPage", "@id": url(path) + "#webpage", "url": url(path), "name": title,
                      "description": description, "inLanguage": "en-US", "isPartOf": {"@id": f"{SITE_URL}/#website"},
                      "breadcrumb": {"@id": url(path) + "#breadcrumb"}})
    graph.append(breadcrumb(path, trail))
