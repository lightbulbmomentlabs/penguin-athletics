def article_graph(art, path, pillar, image):
    m = art["meta"]
    webpage = {"@type": "WebPage", "@id": url(path) + "#webpage", "url": url(path), "name": m["title"],
               "description": m["description"], "inLanguage": "en-US",
               "isPartOf": {"@id": f"{SITE_URL}/#website"}, "breadcrumb": {"@id": url(path) + "#breadcrumb"},
               "primaryImageOfPage": {"@type": "ImageObject", "url": url(image)}, "lastReviewed": updated(art)}
    if m.get("reviewed_by"):
        webpage["reviewedBy"] = {"@type": "Person", "name": m["reviewed_by"]}
    article = {"@type": "Article", "@id": url(path) + "#article", "headline": m["title"],
               "description": m["description"], "abstract": m["answer"],
               "datePublished": m["published"], "dateModified": updated(art), "inLanguage": "en-US",
               "author": {"@id": ORG}, "publisher": {"@id": ORG}, "image": url(image),
               "mainEntityOfPage": {"@id": url(path) + "#webpage"},
               "isPartOf": {"@id": url(page_path(pillar["slug"])) + "#webpage"},
               "about": {"@type": "Thing", "name": pillar["title"]},
               "keywords": m["keywords"], "wordCount": learnlib.word_count(art["main"]),
               "citation": [{"@type": "CreativeWork", "name": learnlib.plain_text(s["text"]), "url": s["url"]}
                            for s in art["sources"]]}
    return [webpage, article]


