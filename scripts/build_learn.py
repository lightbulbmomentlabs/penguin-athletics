# ---------- Feed, sitemap, llms.txt, home teaser ----------

def render_feed(articles):
    items = []
    for a in articles[:30]:
        m = a["meta"]
        d = dt.datetime.fromisoformat(m["published"] + "T12:00:00+00:00")
        items.append(f"""  <item>
    <title>{escape(m['title'])}</title>
    <link>{url(page_path(a['slug']))}</link>
    <guid isPermaLink="true">{url(page_path(a['slug']))}</guid>
    <pubDate>{d.strftime('%a, %d %b %Y %H:%M:%S +0000')}</pubDate>
    <description>{escape(m['answer'])}</description>
  </item>""")
    newest = max([updated(a) for a in articles], default=POLICY_UPDATED)
    build = dt.datetime.fromisoformat(newest + "T12:00:00+00:00").strftime('%a, %d %b %Y %H:%M:%S +0000')
    return f"""<?xml version="1.0" encoding="UTF-8"?>
<rss version="2.0" xmlns:atom="http://www.w3.org/2005/Atom">
<channel>
  <title>Penguin Athletics: Learn</title>
  <link>{url('/learn/')}</link>
  <atom:link href="{url('/learn/feed.xml')}" rel="self" type="application/rss+xml"/>
  <description>Evidence-based guides to the health benefits of walking.</description>
  <language>en-us</language>
  <lastBuildDate>{build}</lastBuildDate>
{chr(10).join(items)}
</channel>
</rss>
"""


def render_sitemap(current, entries):
    """Keep the hand-made non-Learn entries; replace every /learn/ entry."""
    keep = [line for line in current.splitlines()
            if "<url>" in line and f"<loc>{SITE_URL}/learn/" not in line]
    learn = [f"  <url><loc>{url(p)}</loc><lastmod>{d}</lastmod><priority>{pr}</priority></url>"
             for p, d, pr in entries]
    return ('<?xml version="1.0" encoding="UTF-8"?>\n'
            '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
            + "\n".join(keep + learn) + "\n</urlset>\n")


def replace_region(text, start, end, body, where_missing=None):
    """Swap the text between two marker lines. If missing, insert before where_missing (or append)."""
    block = f"{start}\n{body}\n{end}"
    if start in text and end in text:
        return text[:text.index(start)] + block + text[text.index(end) + len(end):]
    if where_missing and where_missing in text:
        i = text.index(where_missing)
        return text[:i] + block + "\n\n" + text[i:]
    return text.rstrip("\n") + "\n\n" + block + "\n"


def render_llms(current, articles, pillars):
    lines = ["## Learn: the health benefits of walking",
             f"Evidence-based, cited articles. Editorial policy: {url(POLICY_PATH)}", ""]
    for k, p in pillars.items():
        lines.append(f"- [{p['title']}]({url(page_path(p['slug']))}): {p['blurb']}")
    lines.append("")
    for a in articles:
        lines.append(f"- [{a['meta']['title']}]({url(page_path(a['slug']))}): {a['meta']['answer']}")
    return replace_region(current, "<!-- learn:start -->", "<!-- learn:end -->", "\n".join(lines).rstrip())


def render_teaser(current, articles, pillars):
    picks = [a for a in articles if a["slug"] not in {p["slug"] for p in pillars.values()}][:3]
    if not picks:
        body = ""
    else:
        body = f"""  <section class="section learn-teaser" aria-labelledby="learn-teaser-title">
    <div class="wrap">
      <span class="kicker">Learn</span>
      <h2 id="learn-teaser-title">Walking, explained. <em>Without the guilt trip.</em></h2>
      <p>What a daily walk actually does for your heart, your lifespan, and your head. Cited, plain-English, answer first.</p>
      {card_list(picks, pillars)}
      <p class="learn-more-links"><a href="/learn/">All articles</a></p>
    </div>
  </section>"""
    return replace_region(current, "  <!-- learn-teaser:start -->", "  <!-- learn-teaser:end -->", body,
                          where_missing='  <section class="section faq"')


# ---------- Build ----------

def build():
    """{path: content} for every generated file, plus validation errors."""
    pillars = load_pillars()
    articles, errors = load_articles(pillars)
    by_slug = {a["slug"]: a for a in articles}
    pillar_slugs = {p["slug"] for p in pillars.values()}
    for a in articles:
        if a["slug"] in pillar_slugs and pillars[a["meta"]["pillar"]]["slug"] != a["slug"]:
            errors.append(f"{a['slug']}: a pillar guide must use its own pillar ({a['slug']})")
    out = {}
    entries = [("/learn/", max([updated(a) for a in articles], default=POLICY_UPDATED), "0.8"),
               (POLICY_PATH, POLICY_UPDATED, "0.3")]
    for p in pillars.values():
        guide = by_slug.get(p["slug"])
        out[LEARN / p["slug"] / "index.html"] = render_pillar(p, guide, articles, pillars)
        members = [updated(a) for a in articles if a["meta"]["pillar"] == p["key"]]
        entries.append((page_path(p["slug"]), max(members, default=POLICY_UPDATED), "0.7"))
    for a in articles:
        if a["slug"] in pillar_slugs:
            continue
        out[LEARN / a["slug"] / "index.html"] = render_article(a, articles, pillars)
        entries.append((page_path(a["slug"]), updated(a), "0.6"))
    out[LEARN / "index.html"] = render_hub(articles, pillars)
    out[LEARN / "feed.xml"] = render_feed(articles)
    for path in out:  # optional template slots (updated date, reviewer) leave blank-ish lines
        out[path] = re.sub(r"\n\s*\n(\s*\n)+", "\n\n", re.sub(r"[ \t]+\n", "\n", out[path]))
    entries.sort(key=lambda e: e[0])
    sitemap, llms, home = PUBLIC / "sitemap.xml", PUBLIC / "llms.txt", PUBLIC / "index.html"
    out[sitemap] = render_sitemap(sitemap.read_text(encoding="utf-8"), entries)
    out[llms] = render_llms(llms.read_text(encoding="utf-8"), articles, pillars)
    out[home] = render_teaser(home.read_text(encoding="utf-8"), articles, pillars)
    return out, errors


def stale_dirs(out):
    """Generated article folders whose source is gone (hand-made pages have no marker)."""
    keep = {p.parent for p in out}
    found = []
    for f in sorted(LEARN.glob("*/index.html")):
        if f.parent not in keep and GENERATED in f.read_text(encoding="utf-8"):
            found.append(f.parent)
    return found


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="report out-of-date files, write nothing")
    args = parser.parse_args()
    out, errors = build()
    if errors:
        for e in errors:
            print("FAIL:", e)
        sys.exit(1)
    changed = [p for p, text in out.items() if not p.exists() or p.read_text(encoding="utf-8") != text]
    gone = stale_dirs(out)
    if args.check:
        for p in changed:
            print("stale:", p.relative_to(ROOT))
        for d in gone:
            print("stale (source deleted):", d.relative_to(ROOT))
        sys.exit(1 if changed or gone else 0)
    for p in changed:
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(out[p], encoding="utf-8")
        print("wrote", p.relative_to(ROOT))
    for d in gone:
        shutil.rmtree(d)
        print("removed", d.relative_to(ROOT))
    if not changed and not gone:
        print("Learn is up to date.")


if __name__ == "__main__":
    main()
