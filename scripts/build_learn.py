def crumbs_html(trail):
    parts = [f'<a href="{p}">{escape(n)}</a>' for p, n in trail[:-1]]
    parts.append(f'<span aria-current="page">{escape(trail[-1][1])}</span>')
    sep = ' <span aria-hidden="true">›</span> '
    return f'<nav class="crumbs" aria-label="Breadcrumb">{sep.join(parts)}</nav>'


def card(art, pillars, heading="h3"):
    m, p = art["meta"], pillars[art["meta"]["pillar"]]
    return (f'<li class="learn-card"><a href="{page_path(art["slug"])}">'
            f'<span class="learn-card-kicker">{escape(p["short"])} · {minutes(art)} min read</span>'
            f'<{heading}>{escape(m["title"])}</{heading}>'
            f'<span class="learn-card-answer">{escape(m["answer"])}</span></a></li>')


def card_list(arts, pillars, heading="h3"):
    return '<ul class="learn-cards">\n' + "\n".join(card(a, pillars, heading) for a in arts) + "\n</ul>"


# ---------- Article and pillar pages ----------

def related(art, articles, pillar_slugs, n=4):
    others = [a for a in articles if a["slug"] != art["slug"] and a["slug"] not in pillar_slugs]
    same = [a for a in others if a["meta"]["pillar"] == art["meta"]["pillar"]]
    rest = [a for a in others if a not in same]
    return (same + rest)[:n]


def article_body(art):
    m = art["meta"]
    reviewed = ""
    if m.get("reviewed_by"):
        reviewed = f'<span>Reviewed by {escape(m["reviewed_by"])}</span>'
    upd = ""
    if updated(art) != m["published"]:
        upd = f'<span>Updated <time datetime="{updated(art)}">{nice_date(updated(art))}</time></span>'
    faq = ""
    if art["faq"]:
        items = "\n".join(f"<details><summary>{escape(q)}</summary>{learnlib.render_markdown(a)}</details>"
                          for q, a in art["faq"])
        faq = f'<section class="faq article-faq" aria-labelledby="faq-title">\n<h2 id="faq-title">FAQ</h2>\n{items}\n</section>'
    sources = ""
    if art["sources"]:
        items = "\n".join(f'<li id="source-{s["n"]}">{learnlib.inline(s["text"])} '
                          f'<a href="{escape(s["url"])}" rel="noopener">{escape(s["url"].split("//", 1)[1].split("/", 1)[0])}</a></li>'
                          for s in art["sources"])
        sources = f'<section class="sources" aria-labelledby="sources-title">\n<h2 id="sources-title">Sources</h2>\n<ol>\n{items}\n</ol>\n</section>'
    return f"""<p class="byline">
      <span>By <a href="{POLICY_PATH}">the Penguin Athletics editorial team</a></span>
      <span>Published <time datetime="{m['published']}">{nice_date(m['published'])}</time></span>
      {upd}
      <span>{minutes(art)} min read</span>
      {reviewed}
    </p>
    <aside class="short-answer" aria-label="The short answer">
      <h2>The short answer</h2>
      <p>{escape(m['answer'])}</p>
    </aside>
    <figure class="gary">
      {pose_img(m['pose'], eager=True)}
      <figcaption><span class="gary-name">Gary's take</span> {escape(m['gary'])}</figcaption>
    </figure>
    <div class="article-body">
{learnlib.render_markdown(art['main'])}
    </div>
    {faq}
    {sources}
    <p class="health-note"><strong>Health note:</strong> {escape(HEALTH_NOTE)}</p>"""


